print(f"Total de filas leídas: {len(df_compania)}")

"""Celda de Código para verificar el total de filas iniciales:

"""

print("¿Hay filas duplicadas?", df_compania.duplicated().any())

print("Número de filas duplicadas:", df_compania.duplicated().sum())

df_compania = df_compania.drop_duplicates()

print(f"Filas después de eliminar duplicados: {len(df_compania)}")

"""Verificamos si existen filas duplicadas en el conjunto de datos y procedemos a eliminarlas para evitar redundancias en nuestro análisis.

"""

print("Valores nulos por columna:")

print(df_compania.isnull().sum())

df_compania = df_compania.dropna(subset=['codigo_empleado', 'nombre_completo', 'departamento', 'salario', 'fecha_ingreso'])

print(f"Filas finales tras limpiar nulos: {len(df_compania)}")

"""Revisamos qué columnas tienen valores nulos y eliminamos aquellos registros incompletos para asegurar la calidad de la información.

"""

print(df_compania.info())

"""Comprobamos con qué tipos de datos estamos trabajando antes de realizar las conversiones necesarias."""

df_compania['codigo_empleado'] = df_compania['codigo_empleado'].astype('string')
df_compania['nombre_completo'] = df_compania['nombre_completo'].astype('string')
df_compania['departamento'] = df_compania['departamento'].astype('string')

df_compania['fecha_ingreso'] = pd.to_datetime(df_compania['fecha_ingreso'], format='%d/%m/%Y')

print(df_compania.dtypes)

"""Convertimos las columnas de texto a tipo string y la columna de fecha a formato datetime para que Power BI y Pandas las interpreten correctamente."""

nombre_archivo_limpio = 'empleados_compañia_limpio.csv'

df_compania.to_csv(nombre_archivo_limpio, index=False)

